import { NextResponse } from 'next/server';
import { isDatabaseConfigured } from '@/db/env';
import { listResearch as listDbResearch } from '@/db/repositories/research-repository';
import { listResearch as listFileResearch } from '@/marcom/memory/research-store';
import { listPersonalizations as listDbPersonalizations } from '@/db/repositories/personalization-repository';
import { listPersonalizations as listFilePersonalizations } from '@/marcom/memory/personalization-store';
import { Project } from '@/types';
import { archiveCampaign, listCampaigns } from '@/db/repositories/campaign-repository';
import { JsonFileMemoryStore } from '@/marcom/memory/store';
import type { ProjectMemory } from '@/marcom/memory/types';
import { authorizeApiRequest } from '@/auth/access';

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export async function GET(req: Request) {
  const access = await authorizeApiRequest(req);
  if (!access.ok) return access.response;
  try {
    let projectMemories: ProjectMemory[] = [];
    let isDb = false;
    const actor = access.actor;

    if (isDatabaseConfigured()) {
      try {
        projectMemories = await listCampaigns(actor);
        isDb = true;
      } catch (e) {
        console.warn('Database error in GET /api/projects, falling back to JSON memory:', e);
      }
    }

    if (!projectMemories || projectMemories.length === 0) {
      try {
        const store = new JsonFileMemoryStore();
        projectMemories = store.projects();
      } catch (e) {
        console.warn('Memory store read error in GET /api/projects:', e);
        projectMemories = [];
      }
    }

    // Map ProjectMemory to the UI Project type
    const projects: Project[] = await Promise.all((projectMemories || []).map(async (pm) => {
      let icon = '📁';
      let accentColor: Project['accentColor'] = 'blue';

      // Infer an icon/color based on name just for visual variety, or fallback
      const lower = (pm.name || '').toLowerCase();
      if (lower.includes('book') || lower.includes('author') || lower.includes('literary')) { icon = '📚'; accentColor = 'pink'; }
      else if (lower.includes('sponsor')) { icon = '🏆'; accentColor = 'purple'; }
      else if (lower.includes('film') || lower.includes('soulbound')) { icon = '🎬'; accentColor = 'blue'; }
      else if (lower.includes('robot') || lower.includes('tech') || lower.includes('launch')) { icon = '🤖'; accentColor = 'blue'; }
      else if (lower.includes('hire') || lower.includes('recruit') || lower.includes('talent')) { icon = '🎯'; accentColor = 'amber'; }
      else if (lower.includes('partner') || lower.includes('sales')) { icon = '🤝'; accentColor = 'blue'; }

      let research = listFileResearch(pm.project_id);
      let personalizations = listFilePersonalizations(pm.project_id);

      if (isDb && actor && UUID_REGEX.test(pm.project_id)) {
        try {
          const dbResearch = await listDbResearch(actor, pm.project_id);
          const dbPersonalizations = await listDbPersonalizations(actor, pm.project_id);
          if (dbResearch.length > 0 || dbPersonalizations.length > 0) {
            research = dbResearch;
            personalizations = dbPersonalizations;
          }
        } catch (e) {
          console.warn('Database error fetching project stats, using memory store fallback:', e);
        }
      }

      const prospectsCurrent = research.length;
      // 100% accurate: count of actual personalized prospects generated by Agent 3
      const qualifiedCount = personalizations.length;
      const reviewCount = research.filter(r => !r.review?.status || r.review?.status === 'needs_review').length;

      const status: Project['status'] = pm.status === 'READY_FOR_RESEARCH'
        ? 'active'
        : pm.status === 'active' || pm.status === 'paused' || pm.status === 'completed'
          ? pm.status
          : 'draft';

      return {
        id: pm.project_id,
        name: pm.name || 'Untitled Project',
        description: pm.summary || pm.structured_brief?.project.description || 'No description provided.',
        prospectsCurrent,
        prospectsTotal: Math.max(100, prospectsCurrent),
        qualifiedCount,
        reviewCount,
        status,
        accentColor,
        icon,
      };
    }));

    return NextResponse.json(projects);
  } catch (error) {
    console.error('Error fetching projects:', error);
    return NextResponse.json({ error: 'Failed to fetch projects' }, { status: 500 });
  }
}

export async function DELETE(req: Request) {
  const access = await authorizeApiRequest(req);
  if (!access.ok) return access.response;
  try {
    const { searchParams } = new URL(req.url);
    const id = searchParams.get('id');

    if (!id) {
      return NextResponse.json({ error: 'Project ID is required' }, { status: 400 });
    }

    let deletedFromDb = false;

    if (isDatabaseConfigured()) {
      try {
        deletedFromDb = await archiveCampaign(access.actor, id);
      } catch (e) {
        if (!access.allowFileFallback) throw e;
        console.warn('Database error in DELETE /api/projects, attempting JSON memory delete.');
      }
    }

    let deletedFromFile = false;
    try {
      const fs = await import('node:fs');
      const path = await import('node:path');

      const memoryDir = path.join(process.cwd(), 'memory');
      const projectsFile = path.join(memoryDir, 'projects.json');

      if (fs.existsSync(projectsFile)) {
        const projects = JSON.parse(fs.readFileSync(projectsFile, 'utf8')) as Array<{ project_id?: string }>;
        const filtered = projects.filter((project) => project.project_id !== id);
        if (filtered.length !== projects.length) {
          fs.writeFileSync(projectsFile, JSON.stringify(filtered, null, 2), 'utf8');
          deletedFromFile = true;
        }
      }

      const origFile = path.join(memoryDir, `${id}-original.json`);
      if (fs.existsSync(origFile)) {
        fs.unlinkSync(origFile);
      }
    } catch {
      // Ignored if local file does not exist
    }

    if (!deletedFromDb && !deletedFromFile) {
      return NextResponse.json({ error: 'Project not found' }, { status: 404 });
    }

    return NextResponse.json({ success: true, message: 'Project deleted successfully' });
  } catch (error) {
    console.error('Error deleting project:', error);
    return NextResponse.json({ error: 'Failed to delete project' }, { status: 500 });
  }
}
